import type { AdCampaign, Lead, Task } from "@/types";
import type { Repository } from "./repository";
import { supabase } from "./supabase";

type Row = Record<string, unknown>;

export class SupabaseRepo<T extends { id: string }> implements Repository<T> {
  constructor(
    private table: string,
    private toRow: (item: Omit<T, "id">) => Row,
    private fromRow: (row: Row) => T,
  ) {}

  async list() {
    const { data, error } = await supabase.from(this.table).select("*").order("created_at", { ascending: true });
    if (error) throw error;
    return (data as Row[]).map(this.fromRow);
  }

  async create(item: Omit<T, "id">) {
    const { data, error } = await supabase.from(this.table).insert(this.toRow(item)).select().single();
    if (error) throw error;
    return this.fromRow(data as Row);
  }

  async update(item: T) {
    const { error } = await supabase.from(this.table).update(this.toRow(item)).eq("id", item.id);
    if (error) throw error;
    return item;
  }

  async remove(id: string) {
    const { error } = await supabase.from(this.table).delete().eq("id", id);
    if (error) throw error;
  }

  async replaceAll(items: T[]) {
    const del = await supabase.from(this.table).delete().not("id", "is", null);
    if (del.error) throw del.error;
    if (items.length === 0) return;
    // Ids are generated by the database, so seed ids are dropped.
    const ins = await supabase.from(this.table).insert(items.map(({ id: _id, ...rest }) => this.toRow(rest as Omit<T, "id">)));
    if (ins.error) throw ins.error;
  }
}

export const leadsRepo = () =>
  new SupabaseRepo<Lead>(
    "leads",
    (l) => ({ customer_name: l.customerName, phone: l.phone, date: l.date, platform: l.platform, machine: l.machine, salesperson: l.salesperson, status: l.status }),
    (r) => ({ id: r.id as string, customerName: r.customer_name as string, phone: r.phone as string, date: r.date as string, platform: r.platform as string, machine: r.machine as string, salesperson: r.salesperson as string, status: r.status as Lead["status"] }),
  );

export const adsRepo = () =>
  new SupabaseRepo<AdCampaign>(
    "ad_campaigns",
    (a) => ({ campaign_name: a.campaignName, platform: a.platform, date: a.date, spend: a.spend, leads: a.leads, sales: a.sales }),
    (r) => ({ id: r.id as string, campaignName: r.campaign_name as string, platform: r.platform as string, date: r.date as string, spend: Number(r.spend), leads: Number(r.leads), sales: Number(r.sales) }),
  );

